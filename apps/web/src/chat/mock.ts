export function createMockHistory(): Message[] {
  const start = Date.now() - historySize * 60_000;
  const firstExample = examples.length - (historySize / 2) % examples.length;
  return Array.from({ length: historySize }, (_, index) => {
    const example = examples[(firstExample + Math.floor(index / 2)) % examples.length]!;
    const assistant = index % 2 === 1;
    return {
      id: index + 1,
      role: assistant ? 'assistant' : 'user',
      text: assistant ? example.reply : example.prompt,
      reasoning: assistant ? example.reasoning : undefined,
      time: start + index * 60_000,
      image: assistant ? example.image : undefined,
    };
  });
}

export function getMockReply(message: Message): MockReply {
  if (/картин|изображен|фото|image/iu.test(message.text)) {
    return { text: stationReply, image: station, reasoning: stationReasoning };
  }
  if (/код|typescript|javascript|\bcode\b/iu.test(message.text)) {
    return { text: codeExample, reasoning: codeReasoning };
  }
  if (/таблиц|\btable\b/iu.test(message.text)) {
    return { text: alternatives, reasoning: tableReasoning };
  }
  if (/чек[- ]?лист|список|план/iu.test(message.text)) {
    return { text: checklist, reasoning: checklistReasoning };
  }
  if (/подроб|глав[ау]|сцен[ау]/iu.test(message.text)) {
    return { text: scene, reasoning: sceneReasoning };
  }
  if (message.image) {
    return {
      text: 'Изображение прикреплено к сообщению. Мок-модель его не анализирует.',
      reasoning: 'Для вложения доступен демонстрационный ответ о получении файла.',
    };
  }
  return {
    text: '**Сообщение получено.** Это ответ мок-модели. Попросите показать код, таблицу или изображение, чтобы проверить их отображение.',
    reasoning: 'Запрос не совпал с примерами кода, таблицы или изображения. Показываю общий демонстрационный ответ.',
  };
}
